await page.locator('[data-mode="catalog"]').click();
const setup=page.getByRole('button',{name:'Настроить состав комплекта',exact:true});
await setup.waitFor({state:'visible'});
assert.equal(await page.locator('.catalog-operations').evaluate(el=>el.open),false);
assert.equal(await setup.evaluate(el=>Boolean(el.closest('details'))),false);
