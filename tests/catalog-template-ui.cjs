let saved;
await page.route('**/api/miniapp/admin/catalog/dependencies',route=>{saved=route.request().postDataJSON();return route.fulfill({json:{ok:true}});});
await setup.click();
await page.getByRole('heading',{name:'Настроить состав комплекта'}).waitFor();
await page.locator('[name="parent_article_id"]').selectOption('1');
await page.locator('[name="child_article_id"]').selectOption('2');
await page.locator('[name="quantity"]').fill('2');
